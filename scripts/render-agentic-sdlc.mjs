const APP_JS = `/* Generated by scripts/render-agentic-sdlc.mjs — edit that script, not this file. */
(() => {
  const root = document.documentElement;
  const themeKey = "copilot-app-docs-theme";

  const storage = {
    get(key) {
      try {
        return localStorage.getItem(key);
      } catch {
        return null;
      }
    },
    set(key, value) {
      try {
        localStorage.setItem(key, value);
      } catch {
        // The page stays usable when storage is blocked.
      }
    },
  };

  function updateThemeToggles() {
    const nextTheme = root.dataset.theme === "dark" ? "light" : "dark";
    document.querySelectorAll("[data-theme-toggle]").forEach((button) => {
      button.setAttribute(
        "aria-label",
        \`\${nextTheme === "dark" ? "ダーク" : "ライト"}テーマに切り替える\`,
      );
      const label = button.querySelector("[data-toggle-label]");
      if (label) label.textContent = nextTheme === "dark" ? "Dark" : "Light";
    });
  }

  function initializeTheme() {
    const queryTheme = new URLSearchParams(window.location.search).get("scoutTheme");
    const storedTheme = storage.get(themeKey);
    if (!queryTheme && (storedTheme === "light" || storedTheme === "dark")) {
      root.dataset.theme = storedTheme;
    }

    document.querySelectorAll("[data-theme-toggle]").forEach((button) => {
      button.addEventListener("click", () => {
        const theme = root.dataset.theme === "dark" ? "light" : "dark";
        root.dataset.theme = theme;
        storage.set(themeKey, theme);
        updateThemeToggles();
      });
    });

    updateThemeToggles();
  }

  function initializeToc() {
    const toc = document.querySelector("[data-toc]");
    if (!toc) return;

    const narrow = window.matchMedia("(max-width: 1023px)");
    const applyViewport = () => {
      toc.open = !narrow.matches;
    };
    applyViewport();
    if (narrow.addEventListener) narrow.addEventListener("change", applyViewport);
    else if (narrow.addListener) narrow.addListener(applyViewport);

    const links = Array.from(toc.querySelectorAll(".toc__list a"));
    const linkById = new Map(links.map((link) => [link.getAttribute("href").slice(1), link]));
    const sections = Array.from(document.querySelectorAll("section.section"));

    const setActive = (id) => {
      links.forEach((link) => link.removeAttribute("aria-current"));
      const link = linkById.get(id);
      if (!link) return;
      link.setAttribute("aria-current", "true");
      if (!narrow.matches && link.scrollIntoView) link.scrollIntoView({ block: "nearest" });
    };

    links.forEach((link) => {
      link.addEventListener("click", () => {
        setActive(link.getAttribute("href").slice(1));
        if (narrow.matches) toc.open = false;
      });
    });

    if (!sections.length || !("IntersectionObserver" in window)) return;

    const visible = new Set();
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) visible.add(entry.target.id);
          else visible.delete(entry.target.id);
        });
        // The reading band can hold two neighbours at once; the later one is the
        // section being scrolled into, so it wins.
        for (let index = sections.length - 1; index >= 0; index -= 1) {
          if (visible.has(sections[index].id)) {
            setActive(sections[index].id);
            break;
          }
        }
      },
      { rootMargin: "-12% 0px -70% 0px", threshold: 0 },
    );

    sections.forEach((section) => observer.observe(section));
  }

  initializeTheme();
  initializeToc();
})();
`;

const themeScript = `<script>
  (() => {
    const param = new URLSearchParams(window.location.search).get("scoutTheme");
    let theme = param === "light" || param === "dark" ? param : null;
    if (!theme) {
      try {
        const stored = localStorage.getItem("copilot-app-docs-theme");
        if (stored === "light" || stored === "dark") theme = stored;
      } catch {
        theme = null;
      }
    }
    if (!theme) {
      theme = window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
    }
    document.documentElement.setAttribute("data-theme", theme);
  })();
</script>`;

function renderToc() {
  const bySection = new Map(sections.map((section) => [section.id, section]));
  const groups = parts
    .map((part) => {
      const items = part.ids
        .map((id) => bySection.get(id))
        .map(
          (section) =>
            `        <li><a href="#${section.id}"><span class="toc__num">${escapeHtml(section.num)}</span><span>${escapeHtml(section.title)}</span></a></li>`,
        )
        .join("\n");
      return `      <li class="toc__part">
        <p class="toc__part-title">${escapeHtml(part.title)}</p>
        <ul class="toc__list">
${items}
        </ul>
      </li>`;
    })
    .join("\n");

  return `<details class="toc" data-toc open>
  <summary class="toc__summary">${svg(icons.list)}<span>目次 — 全 ${sections.length} 節</span></summary>
  <nav aria-label="セクション">
    <p class="toc__title">目次</p>
    <ul class="toc__parts">
${groups}
    </ul>
  </nav>
  <p class="toc__foot">${escapeHtml(meta.verified)}<br>Public Preview 表記の機能は仕様変更の可能性があります。</p>
</details>`;
}

